function makeStats(
  playerId: string,
  jogos: number,
  vitorias: number,
  empates: number,
  gols: number,
  assistencias: number,
  golsContra: number,
  mvps: number,
): PlayerStats {
  const derrotas = jogos - vitorias - empates;
  const aproveitamento = Math.round(((vitorias * 3 + empates) / (jogos * 3)) * 100);
  return {
    playerId,
    jogos,
    vitorias,
    empates,
    derrotas,
    gols,
    assistencias,
    golsContra,
    participacoesEmGols: gols + assistencias,
    mediaGolsPorJogo: Number((gols / jogos).toFixed(2)),
    mediaAssistenciasPorJogo: Number((assistencias / jogos).toFixed(2)),
    aproveitamento,
    mvps,
  };
}

